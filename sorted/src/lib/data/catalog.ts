import { IMAGES } from "@/lib/data/images";
import type { Catalog, DinnerBundle, Restaurant } from "@/lib/types";

const AT = "2026-08-01T00:00:00.000Z";
const DAYS = ["mon", "tue", "wed", "thu", "fri", "sat", "sun"];

export function rid(n: number): string {
  return `00000000-0000-4000-a000-${String(n).padStart(12, "0")}`;
}

export function bid(n: number): string {
  return `00000000-0000-4000-b000-${String(n).padStart(12, "0")}`;
}

function restaurant(
  n: number,
  fields: Omit<Restaurant, "id" | "active" | "created_at">,
): Restaurant {
  return { id: rid(n), active: true, created_at: AT, ...fields };
}

function bundle(
  n: number,
  restaurantN: number,
  fields: Omit<DinnerBundle, "id" | "restaurant_id" | "active" | "available_days" | "created_at">,
): DinnerBundle {
  return {
    id: bid(n),
    restaurant_id: rid(restaurantN),
    active: true,
    available_days: DAYS,
    created_at: AT,
    ...fields,
  };
}

