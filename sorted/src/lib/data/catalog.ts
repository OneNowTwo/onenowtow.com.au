import { IMAGES, type ImageKey } from "@/lib/data/images";
import type { Catalog, DinnerBundle, Restaurant } from "@/lib/types";

const AT = "2026-08-01T00:00:00.000Z";
const ALL = ["mon", "tue", "wed", "thu", "fri", "sat", "sun"];

export function rid(n: number): string {
  return `00000000-0000-4000-a000-${String(n).padStart(12, "0")}`;
}

export function bid(n: number): string {
  return `00000000-0000-4000-b000-${String(n).padStart(12, "0")}`;
}

function restaurant(
  n: number,
  name: string,
  slug: string,
  description: string,
  address: string,
  cuisine: string,
  orderingUrl: string,
  image: ImageKey,
  openingHours: string,
): Restaurant {
  return {
    id: rid(n),
    name,
    slug,
    description,
    address,
    suburb: "Manly",
    postcode: "2095",
    cuisine,
    image_url: IMAGES[image],
    ordering_url: orderingUrl,
    official_url: orderingUrl,
    verified: true,
    dinner_suitable: true,
    opening_hours: openingHours,
    active: true,
    created_at: AT,
  };
}

interface PackConcept {
  name: string;
  description: string;
  price: number;
  feedsPeople: number;
  estimatedMinutes: number;
  image: ImageKey;
  tags: string[];
  dietaryTags: string[];
}

function pack(
  name: string,
  description: string,
  price: number,
  feedsPeople: number,
  estimatedMinutes: number,
  image: ImageKey,
  tags: string[],
  dietaryTags: string[] = [],
): PackConcept {
  return {
    name,
    description,
    price,
    feedsPeople,
    estimatedMinutes,
    image,
    tags,
    dietaryTags,
  };
}

function bundle(
  n: number,
  restaurantN: number,
  concept: PackConcept,
  availableDays: string[] = ALL,
): DinnerBundle {
  return {
    id: bid(n),
    restaurant_id: rid(restaurantN),
    name: concept.name,
    description: concept.description,
    price: concept.price,
    feeds_people: concept.feedsPeople,
    estimated_minutes: concept.estimatedMinutes,
    image_url: IMAGES[concept.image],
    active: true,
    available_days: availableDays,
    tags: concept.tags,
    dietary_tags: concept.dietaryTags,
    is_concept_bundle: true,
    created_at: AT,
  };
}

